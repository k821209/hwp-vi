//! 기호 표 — **코퍼스가 실제로 쓰는 것**을 센 결과로 짰다.
//!
//! 터미널에는 한글 IME 가 있어도 `○` `□` `※` `①` 같은 기호를 넣을 길이 없다.
//! 두벌식 오토마톤은 한글만 만든다. HWP 는 이 일을 **문자표**(`Ctrl-F10`)로
//! 하고, 공문서는 그 기호들로 계층을 만든다 — 그래서 없으면 공문서를 쓸 수 없다.
//!
//! **무엇을 담을지 짐작하지 않았다.** 코퍼스 14개 문서의 본문과 표 칸에서
//! 한글·한자·ASCII 를 뺀 글자를 전수로 세었다 (2026-10-11, 서로 다른 기호 57개):
//!
//! ```text
//! ·  165   ○  128   □  123   ’   90   ◦   53   ※   50
//! ×   26   •   17   –   15   ◾   14   ∼   14   ▶   13
//! →   13   ①    8   ②    8   「」  7   ③    6   ☞    5
//! ```
//!
//! 그래서 **글머리가 첫 묶음**이고 그 안에서도 `○ □ ◦ ※` 가 앞이다. 쓰지도
//! 않는 기호를 가나다순으로 늘어놓으면 매번 찾아 헤매게 된다.
//!
//! 담지 않은 것 둘:
//!
//! - **사용자 영역**(`U+F007E`, `U+F02B1`~`U+F02B4`, 코퍼스에 6번). 한컴 글꼴의
//!   자체 글립이라 다른 곳에 붙이면 네모로 보인다. 넣을 기호가 아니다.
//! - `U+2007`(FIGURE SPACE, 74번)·`U+2024`(ONE DOT LEADER). 공백과 마침표의
//!   변종이라 **골라 넣는 것**이 아니다 — 글자처럼 보이는데 아니어서 더 나쁘다.
//!
//! 반각 변종(`･` `｢` `｣`)은 **담았다.** 전각과 거의 똑같이 보여 눈으로는 가릴
//! 수 없지만 코퍼스가 쓰고 있고, 그 문서를 고치는 사람은 같은 글자로 이어 써야
//! 한다. 뜻에 "반각" 을 적어 가른다 — 처음엔 뺐다가 코퍼스 대조 시험이 잡았다.

